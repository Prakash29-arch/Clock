UPM, PITCH, DOT, ADV = 1000, 100, 74, 620
X0 = (ADV - (4 * PITCH + DOT)) // 2          # left bearing so 5 cols are centred
R = DOT / 2.0

def dot(pen, cx, cy):
    # closed contour made only of off-curve points = a smooth quadratic circle
    n = 8
    pts = []
    k = R / math.cos(math.pi / n)                 # tangent-polygon radius for exact circle tangency
    for i in range(n):
        a = 2 * math.pi * (i + 0.5) / n
        pts.append((round(cx + k * math.cos(a)), round(cy + k * math.sin(a))))
    pen.qCurveTo(*pts, None)
    pen.closePath()

def glyph(rows):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch == '#':
                dot(pen, X0 + R + c * PITCH, R + (6 - r) * PITCH)
    return pen.glyph()

